<p>
  鮮やかなメキシコの響きに続き、本演奏会は一転して暗闇へと誘われる。フランスの作曲家サン=サーンスの代表作、交響詩《死の舞踏》である。「フランスのモーツァルト」と称されるほどの神童であったサン=サーンスは、リストが創始した「交響詩」というジャンルをフランス音楽界に積極的に取り入れた人物でもあった。
</p>

<p>
  本作は、フランスの詩人アンリ・カザリスの怪奇的な詩に着想を得た交響詩である。サン＝サーンスはまず1872年に歌曲としてこの詩にメロディーを与え、その後1874年に管弦楽による歌のない交響詩へと発展させた。スコアの冒頭には、カザリスの詩から数行が引用されている。
</p>

