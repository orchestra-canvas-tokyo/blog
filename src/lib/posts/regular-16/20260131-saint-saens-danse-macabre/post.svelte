<p>
  「死の舞踏（Danse
  Macabre）」は中世以来の伝統的な美術のモチーフであり、身分や貧富の差を超えて全ての人間に平等に訪れる死を象徴してきた。サン=サーンスは、この普遍的なテーマに対し、革新的な音響と巧みな管弦楽法によって独自の音楽的解釈を与えている。
</p>

<p>
  ハープが午前0時の到来を告げ、死神に扮した独奏ヴァイオリンが登場する。このヴァイオリンはE線（最高弦）を半音下げてE♭に合わせるスコルダトゥーラ（変則調弦）を施されており、死神が調弦をするかのように、開放弦でラとミ♭の不協和音を鳴らす。このラ–ミ♭の音程はトライトーン（減5度または増4度、三全音）であり、中世より「悪魔の音程」として忌み嫌われてきた響きである。調性の中心を曖昧にするこの不吉な音程は、後の20世紀音楽における調性解体の萌芽を内包している。
</p>

<p>
  死神に誘われ、フルートが魔法にかかったような主題を提示し、骸骨たちの狂乱の踊りが始まる。シロフォン（木琴）が骨の触れ合う音を模倣し、軽妙なリズムと鋭い管弦楽法が、グロテスクでありながら諧謔的な雰囲気を醸し出す。ワルツは次第に熱を帯び、狂乱の極みに達するが、突如、オーボエが夜明けを告げる雄鶏の鳴き声を模すと、饗宴は終局を迎える。骸骨たちは慌てて墓へと戻り、死神が名残惜しそうに最後の旋律を奏でると、朝の静寂の中に音楽は消え入るように終わる。
</p>

<p>
  初演当時、変則調弦や不協和音の多用が物議を醸したが、やがて本作は広く受け入れられ、今日まで愛され続けている。サン=サーンスが描いた「死の踊り」は、恐怖だけでなく、どこか滑稽で人間的な側面をも併せ持つ。それは、死を忌避するのではなく、むしろ生の一部として受け入れようとする、フランス的な精神性の表れなのかもしれない。
</p>

