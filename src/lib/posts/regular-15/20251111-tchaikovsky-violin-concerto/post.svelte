<h4>第2楽章　<i>Canzonetta</i>: Andante　ト短調</h4>

<p>
  3部形式のカンツォネッタである。管楽器の導入に続いて独奏ヴァイオリンが悲しげで憧れに満ちた主題（譜例4）を奏でる。中間部は感情の起伏を見せつつ新たな主題（譜例5）が曲に変化をもたらし、豊かな歌を繰り広げる。コーダはオーケストラだけで静かに奏でられて締められる。
</p>

