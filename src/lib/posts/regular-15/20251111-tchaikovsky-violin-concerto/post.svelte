<p>
  1870年代のロシアは、国民の苦悩が鮮明に浮かび上がった時代であった。知識階層の学生たちは、民衆の犠牲のうえに大学で学ぶことに罪の意識を抱き、「ヴ・ナロード（人民の中へ）」運動を展開し、農民に対する社会革命思想のプロパガンダに注力した。そこには、未来を切り開くために苦しみを渇望するかのような姿勢があったといえる。
</p>

<p>
  一方、こうした苦悩を超えて未来の成功を得ようとする姿勢は、社会的理想主義としてだけでなく個人の創作活動にも現れた。オネーギンといったロシア19世紀文学の主要な主人公たちがほとんど全て「敗北の人」であることはその代表的な例である。そしてチャイコフスキーの場合は、個人的苦悩を創作へと昇華する姿勢において、ヴ・ナロードを展開した学生らとの同質性があり、その結晶こそが本作品であるといえよう。
</p>

<h3>作曲背景と初演</h3>

<p>
  作曲前年となる1877年、チャイコフスキーは結婚に踏み切ったが数週間で破綻し、深刻な精神的危機に陥ってしまった。しかし、後援者のフォン・メック夫人の経済的援助と手紙による精神的支えにより、彼は再び音楽に向かう力を取り戻す。旅行中に耳にしたラロの《スペイン交響曲》にも触発され、1878年春、スイスのクラレンス滞在中に一気に書き上げられたのが本作品である。フォン・メック夫人お抱えのヴァイオリニストであったコーチェクの技術的助言も完成に大きく寄与した。
</p>

<p>
  当初、本作品はレオポルド・アウアーに献呈される予定だったが、演奏不能として拒否されてしまった。初演は1881年、ウィーンでアドルフ・ブロツキーの独奏により実現したとされる。ブロツキーが積極的に演奏したことにより、本作品は次第に欧州で高い評価を獲得した。結局アウアーも態度を翻して演奏するようになり、やがて本作品はヴァイオリン協奏曲の中核をなす存在として成功を収めたのである。
</p>

<h3>楽曲解説</h3>

<p>3楽章から成る楽曲である。</p>

<h4>第1楽章 　Allegro moderato – Moderato assai　ニ長調</h4>

<p>
  序奏を持つソナタ形式である。第1ヴァイオリンが語りかけるような序奏主題を奏で、オーケストラが合いの手を入れる（譜例1）。盛り上がった後にソナタ主部に入り、独奏ヴァイオリンが伸びやかな第1主題（譜例2）を歌い出す。華やかな展開を経て、しみじみとした第2主題（譜例3）も提示される。起伏に富んだ展開部の後にカデンツァが奏でられる。再現部を経て楽章は力強いコーダで締め括られる。
</p>

