<h4>第3楽章　<i>Finale</i>: Allegro vivacissimo　ニ長調</h4>

<p>
  ソナタ風の要素を加味したロンド形式である。オーケストラが第1主題を予感させ、独奏ヴァイオリンが単独で発展させる。ついに独奏ヴァイオリンが歯切れ良い第1主題（譜例6）に至る。ロシア舞曲的で活気を持った第2主題（譜例7）は少しテンポを落として奏でられ、次第に緊迫感を増していく。第1主題の再現、第2主題の再現、第1主題の三現をへて、華麗で壮麗な楽曲は熱狂的な盛り上がりのうちに終わる。
</p>

